// Generates src/lib/bg-lab/engine/bluenoise.ts — a 128x128 blue-noise threshold
// matrix via Ulichney's void-and-cluster (torus-wrapped Gaussian, sigma 1.9,
// deterministic seed). Emitted as a shared TS module so the CPU dither op and
// the GL dither pass read IDENTICAL bytes (exact parity, no async asset load).
// Rerun: node scripts/gen-bluenoise.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const S = 128;
const N = S * S;
const SIGMA = 1.9;

// mulberry32 — deterministic PRNG
function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rand = mulberry32(1);

// wrapped Gaussian kernel by (dy,dx)
const K = new Float64Array(N);
for (let dy = 0; dy < S; dy++)
  for (let dx = 0; dx < S; dx++) {
    const wx = Math.min(dx, S - dx);
    const wy = Math.min(dy, S - dy);
    K[dy * S + dx] = Math.exp(-(wx * wx + wy * wy) / (2 * SIGMA * SIGMA));
  }

// energy field ops: splat(i, +1|-1) adds/removes a point's kernel into E
function makeField() {
  return new Float64Array(N);
}
function splat(E, i, sign) {
  const iy = (i / S) | 0;
  const ix = i % S;
  for (let y = 0; y < S; y++) {
    const row = (((y - iy) % S) + S) % S * S;
    const yb = y * S;
    for (let x = 0; x < S; x++) {
      E[yb + x] += sign * K[row + ((((x - ix) % S) + S) % S)];
    }
  }
}
const argOf = (E, mask, want, cmp) => {
  let best = -1;
  let bv = cmp > 0 ? -Infinity : Infinity;
  for (let i = 0; i < N; i++) {
    if (mask[i] !== want) continue;
    const v = E[i];
    if (cmp > 0 ? v > bv : v < bv) {
      bv = v;
      best = i;
    }
  }
  return best;
};
const tightestCluster = (E, on) => argOf(E, on, 1, +1); // max energy among 1s
const largestVoid = (E, on) => argOf(E, on, 0, -1); // min energy among 0s

// 1. initial pattern: N/10 random points
const on = new Uint8Array(N);
const E = makeField();
const N1 = Math.floor(N / 10);
let placed = 0;
while (placed < N1) {
  const i = Math.floor(rand() * N);
  if (on[i]) continue;
  on[i] = 1;
  splat(E, i, +1);
  placed++;
}

// 2. relax: move tightest cluster point into largest void until stable
for (let iter = 0; iter < N; iter++) {
  const c = tightestCluster(E, on);
  on[c] = 0;
  splat(E, c, -1);
  const v = largestVoid(E, on);
  on[v] = 1;
  splat(E, v, +1);
  if (v === c) break;
}

const rank = new Int32Array(N).fill(-1);

// phase 1: peel the prototype down, ranks N1-1..0
{
  const p = on.slice();
  const pe = E.slice();
  for (let r = N1 - 1; r >= 0; r--) {
    const c = tightestCluster(pe, p);
    p[c] = 0;
    splat(pe, c, -1);
    rank[c] = r;
  }
}

// phase 2: fill voids from the prototype up to half, ranks N1..N/2-1
{
  for (let r = N1; r < N / 2; r++) {
    const v = largestVoid(E, on);
    on[v] = 1;
    splat(E, v, +1);
    rank[v] = r;
  }
}

// phase 3: majority-1s regime — insert into the largest cluster of 0s,
// tracked with the complement pattern's energy field.
{
  const E0 = makeField();
  for (let i = 0; i < N; i++) if (!on[i]) splat(E0, i, +1);
  for (let r = N / 2; r < N; r++) {
    const c = argOf(E0, on, 0, +1); // max 0-energy among 0s
    on[c] = 1;
    splat(E0, c, -1);
    rank[c] = r;
  }
}

// sanity: every pixel ranked exactly once
{
  const seen = new Uint8Array(N);
  for (let i = 0; i < N; i++) {
    if (rank[i] < 0 || rank[i] >= N || seen[rank[i]]) throw new Error("bad ranking at " + i);
    seen[rank[i]] = 1;
  }
}

// quantize rank 0..16383 -> byte 0..255 (dither thresholds don't need 14 bits)
const bytes = Buffer.alloc(N);
for (let i = 0; i < N; i++) bytes[i] = rank[i] >> 6;

const b64 = bytes.toString("base64");
const out = `// GENERATED by scripts/gen-bluenoise.mjs — do not edit by hand.
// 128x128 blue-noise threshold matrix (void-and-cluster, torus Gaussian
// sigma ${SIGMA}, seed 1), rank-quantized to bytes 0..255. Shared by the CPU
// dither op (util.ts orderedThreshold) and the GL dither pass (u_bn texture)
// so both engines threshold against IDENTICAL values — exact parity, and no
// async asset load in the synchronous CPU op. Threshold = (v + 0.5) / 256.
export const BLUE_NOISE_SIZE = ${S};
const B64 =
  "${b64.replace(/(.{100})/g, '$1" +\n  "')}";
function decode(s: string): Uint8Array {
  const bin = atob(s);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}
export const BLUE_NOISE_128: Uint8Array = decode(B64);
`;

const here = dirname(fileURLToPath(import.meta.url));
const dest = join(here, "..", "src", "lib", "bg-lab", "engine", "bluenoise.ts");
writeFileSync(dest, out);
console.log("wrote", dest, "bytes:", bytes.length, "b64 chars:", b64.length);
